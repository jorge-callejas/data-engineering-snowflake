USE DATABASE MEETUP_DB;
USE SCHEMA SILVER;

INSERT INTO QUARANTINE.CATEGORIES_QUARANTINE
(
    CATEGORY_ID,
    CATEGORY_NAME,
    SHORTNAME,
    SORT_NAME,
    REJECTION_REASON,
    PIPELINE_RUN_ID
)
SELECT
    CATEGORY_ID,
    CATEGORY_NAME,
    SHORTNAME,
    SORT_NAME,
    'CATEGORY_ID_IS_NULL',
    '{pipeline_run_id}'
FROM BRONZE.CATEGORIES_RAW
WHERE CATEGORY_ID IS NULL;


MERGE INTO SILVER.CATEGORIES_SILVER AS T

USING
(   
    WITH CATEGORIES AS
    (
        SELECT
            CATEGORY_ID,
            CATEGORY_NAME,
            SHORTNAME,
            SORT_NAME,
            ROW_NUMBER() OVER (
                PARTITION BY CATEGORY_ID
                ORDER BY CATEGORY_ID
            ) AS RN
        FROM BRONZE.CATEGORIES_RAW
    )
    SELECT
        CATEGORY_ID,
        CATEGORY_NAME,
        COALESCE(
            SHORTNAME,
            SPLIT_PART(CATEGORY_NAME,' ',1)
        ) AS SHORTNAME,
        COALESCE(
            SORT_NAME,
            CATEGORY_NAME
        ) AS SORT_NAME
    FROM CATEGORIES
    WHERE RN = 1 AND CATEGORY_ID IS NOT NULL
) AS S

ON T.CATEGORY_ID = S.CATEGORY_ID

WHEN MATCHED 
AND (
       COALESCE(T.CATEGORY_NAME,'') <> COALESCE(S.CATEGORY_NAME,'')
    OR COALESCE(T.SHORTNAME,'') <> COALESCE(S.SHORTNAME,'')
    OR COALESCE(T.SORT_NAME,'') <> COALESCE(S.SORT_NAME,'')
)
THEN
UPDATE SET

    T.CATEGORY_NAME = S.CATEGORY_NAME,
    T.SHORTNAME = S.SHORTNAME,
    T.SORT_NAME = S.SORT_NAME,
    T.UPDATED_TIMESTAMP = CURRENT_TIMESTAMP(),
    T.PIPELINE_RUN_ID = '{pipeline_run_id}'

WHEN NOT MATCHED THEN
INSERT
(
    CATEGORY_ID,
    CATEGORY_NAME,
    SHORTNAME,
    SORT_NAME,
    PIPELINE_RUN_ID
)
VALUES
(
    S.CATEGORY_ID,
    S.CATEGORY_NAME,
    S.SHORTNAME,
    S.SORT_NAME,
    '{pipeline_run_id}'
);