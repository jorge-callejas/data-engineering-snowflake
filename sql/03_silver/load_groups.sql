            ORGANIZER_PHOTO_PHOTO_ID,
            ORGANIZER_PHOTO_PHOTO_LINK,
            ORGANIZER_PHOTO_THUMB_LINK,
            ORGANIZER_PHOTO_TYPE,

            RATING,
            STATE,
            TIMEZONE,

            URLNAME,
            UTC_OFFSET,

            VISIBILITY,
            WHO,

            ROW_NUMBER() OVER
            (
                PARTITION BY GROUP_ID
                ORDER BY LOAD_TIMESTAMP DESC
            ) AS RN

        FROM BRONZE.GROUPS_RAW
    )

    SELECT
        GROUP_ID,
        CATEGORY_ID,
        CATEGORY_NAME,
        CATEGORY_SHORTNAME,
        CITY_ID,
        CITY,
        COUNTRY,
        CREATED,
        DESCRIPTION,

        GROUP_PHOTO_BASE_URL,
        GROUP_PHOTO_HIGHRES_LINK,
        GROUP_PHOTO_PHOTO_ID,
        GROUP_PHOTO_PHOTO_LINK,
        GROUP_PHOTO_THUMB_LINK,
        GROUP_PHOTO_TYPE,

        JOIN_MODE,
        LAT,
        LINK,
        LON,

        MEMBERS,

        GROUP_NAME,

        ORGANIZER_MEMBER_ID,
        ORGANIZER_NAME,

        ORGANIZER_PHOTO_BASE_URL,
        ORGANIZER_PHOTO_HIGHRES_LINK,
        ORGANIZER_PHOTO_PHOTO_ID,
        ORGANIZER_PHOTO_PHOTO_LINK,
        ORGANIZER_PHOTO_THUMB_LINK,
        ORGANIZER_PHOTO_TYPE,

        RATING,
        STATE,
        TIMEZONE,

        URLNAME,
        UTC_OFFSET,

        VISIBILITY,
        WHO

    FROM GROUPS_DATA
    WHERE RN = 1
      AND GROUP_ID IS NOT NULL
      AND CATEGORY_ID IS NOT NULL
      AND CITY_ID IS NOT NULL

) AS S

ON T.GROUP_ID = S.GROUP_ID

WHEN MATCHED
AND (
       COALESCE(T.GROUP_NAME,'') <> COALESCE(S.GROUP_NAME,'')
    OR COALESCE(T.CATEGORY_NAME,'') <> COALESCE(S.CATEGORY_NAME,'')
    OR COALESCE(T.CITY,'') <> COALESCE(S.CITY,'')
    OR COALESCE(T.COUNTRY,'') <> COALESCE(S.COUNTRY,'')
    OR COALESCE(T.MEMBERS,-1) <> COALESCE(S.MEMBERS,-1)
    OR COALESCE(T.RATING,-1) <> COALESCE(S.RATING,-1)
    OR COALESCE(T.VISIBILITY,'') <> COALESCE(S.VISIBILITY,'')
    OR COALESCE(T.URLNAME,'') <> COALESCE(S.URLNAME,'')
)

