MERGE INTO SILVER.GROUPS_SILVER AS T

USING
(
    WITH GROUPS_DATA AS
    (
        SELECT
            GROUP_ID,
            CATEGORY_ID,
            CATEGORY_NAME,
            CATEGORY_SHORTNAME,
            CITY_ID,
            CITY,
            COUNTRY,
