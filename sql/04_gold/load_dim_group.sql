USE DATABASE MEETUP_DB;
USE SCHEMA GOLD;

MERGE INTO GOLD.DIM_GROUP AS T

USING
(
    SELECT
        GROUP_ID,
        GROUP_NAME,
        CATEGORY_ID,
        CATEGORY_NAME,
        CITY_ID,
        MEMBERS,
        RATING
    FROM SILVER.GROUPS_SILVER
) AS S

ON T.GROUP_ID = S.GROUP_ID

WHEN MATCHED
AND (
       COALESCE(T.GROUP_NAME,'') <> COALESCE(S.GROUP_NAME,'')
    OR COALESCE(T.CATEGORY_ID,-1) <> COALESCE(S.CATEGORY_ID,-1)
    OR COALESCE(T.CATEGORY_NAME,'') <> COALESCE(S.CATEGORY_NAME,'')
    OR COALESCE(T.CITY_ID,-1) <> COALESCE(S.CITY_ID,-1)
    OR COALESCE(T.MEMBERS,-1) <> COALESCE(S.MEMBERS,-1)
    OR COALESCE(T.RATING,-1) <> COALESCE(S.RATING,-1)
)

THEN UPDATE SET

    T.GROUP_NAME = S.GROUP_NAME,
    T.CATEGORY_ID = S.CATEGORY_ID,
    T.CATEGORY_NAME = S.CATEGORY_NAME,
    T.CITY_ID = S.CITY_ID,
    T.MEMBERS = S.MEMBERS,
    T.RATING = S.RATING

WHEN NOT MATCHED THEN

INSERT
(
    GROUP_ID,
    GROUP_NAME,
    CATEGORY_ID,
    CATEGORY_NAME,
    CITY_ID,
    MEMBERS,
    RATING
)
VALUES
(
    S.GROUP_ID,
    S.GROUP_NAME,
    S.CATEGORY_ID,
    S.CATEGORY_NAME,
    S.CITY_ID,
    S.MEMBERS,
    S.RATING
);