USE DATABASE MEETUP_DB;
USE SCHEMA GOLD;

MERGE INTO GOLD.DIM_CITY T

USING
(
    SELECT
        CITY_ID,
        CITY,
        COUNTRY,
        STATE,
        ZIP
    FROM SILVER.CITIES_SILVER
) S

ON T.CITY_ID = S.CITY_ID

WHEN MATCHED
AND (
       COALESCE(T.CITY,'') <> COALESCE(S.CITY,'')
    OR COALESCE(T.COUNTRY,'') <> COALESCE(S.COUNTRY,'')
    OR COALESCE(T.STATE,'') <> COALESCE(S.STATE,'')
    OR COALESCE(T.ZIP,'') <> COALESCE(S.ZIP,'')
)

THEN UPDATE SET

    T.CITY = S.CITY,
    T.COUNTRY = S.COUNTRY,
    T.STATE = S.STATE,
    T.ZIP = S.ZIP

WHEN NOT MATCHED THEN

INSERT
(
    CITY_ID,
    CITY,
    COUNTRY,
    STATE,
    ZIP
)
VALUES
(
    S.CITY_ID,
    S.CITY,
    S.COUNTRY,
    S.STATE,
    S.ZIP
);