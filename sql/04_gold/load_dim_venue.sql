USE DATABASE MEETUP_DB;
USE SCHEMA GOLD;

MERGE INTO GOLD.DIM_VENUE AS T

USING
(
    SELECT
        VENUE_ID,
        VENUE_NAME,
        CITY,
        COUNTRY,
        STATE
    FROM SILVER.VENUES_SILVER
) AS S

ON T.VENUE_ID = S.VENUE_ID

WHEN MATCHED
AND (
       COALESCE(T.VENUE_NAME,'') <> COALESCE(S.VENUE_NAME,'')
    OR COALESCE(T.CITY,'') <> COALESCE(S.CITY,'')
    OR COALESCE(T.COUNTRY,'') <> COALESCE(S.COUNTRY,'')
    OR COALESCE(T.STATE,'') <> COALESCE(S.STATE,'')
)

THEN UPDATE SET

    T.VENUE_NAME = S.VENUE_NAME,
    T.CITY = S.CITY,
    T.COUNTRY = S.COUNTRY,
    T.STATE = S.STATE

WHEN NOT MATCHED THEN

INSERT
(
    VENUE_ID,
    VENUE_NAME,
    CITY,
    COUNTRY,
    STATE
)
VALUES
(
    S.VENUE_ID,
    S.VENUE_NAME,
    S.CITY,
    S.COUNTRY,
    S.STATE
);