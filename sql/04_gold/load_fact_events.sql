USE DATABASE MEETUP_DB;
USE SCHEMA GOLD;

MERGE INTO GOLD.FACT_EVENTS T

USING
(
    SELECT

        E.EVENT_ID,

        D.DATE_KEY,

        G.GROUP_KEY,

        V.VENUE_KEY,

        E.YES_RSVP_COUNT,
        E.MAYBE_RSVP_COUNT,
        E.WAITLIST_COUNT,
        E.HEADCOUNT,

        E.RATING_AVERAGE

    FROM SILVER.EVENTS_SILVER E

    INNER JOIN GOLD.DIM_DATE D
        ON D.DATE_KEY =
        TO_NUMBER(
            TO_CHAR(
                CAST(E.EVENT_TIME AS DATE),
                'YYYYMMDD'
            )
        )

    INNER JOIN GOLD.DIM_GROUP G
        ON G.GROUP_ID = E.GROUP_ID

    LEFT JOIN GOLD.DIM_VENUE V
        ON V.VENUE_ID = E.VENUE_ID

) S

ON T.EVENT_ID = S.EVENT_ID

WHEN MATCHED
AND (
       COALESCE(T.DATE_KEY,-1) <> COALESCE(S.DATE_KEY,-1)
    OR COALESCE(T.GROUP_KEY,-1) <> COALESCE(S.GROUP_KEY,-1)
    OR COALESCE(T.VENUE_KEY,-1) <> COALESCE(S.VENUE_KEY,-1)
    OR COALESCE(T.YES_RSVP_COUNT,-1) <> COALESCE(S.YES_RSVP_COUNT,-1)
    OR COALESCE(T.MAYBE_RSVP_COUNT,-1) <> COALESCE(S.MAYBE_RSVP_COUNT,-1)
    OR COALESCE(T.WAITLIST_COUNT,-1) <> COALESCE(S.WAITLIST_COUNT,-1)
    OR COALESCE(T.HEADCOUNT,-1) <> COALESCE(S.HEADCOUNT,-1)
    OR COALESCE(T.RATING_AVERAGE,-1) <> COALESCE(S.RATING_AVERAGE,-1)
)

THEN UPDATE SET

    T.DATE_KEY = S.DATE_KEY,
    T.GROUP_KEY = S.GROUP_KEY,
    T.VENUE_KEY = S.VENUE_KEY,

    T.YES_RSVP_COUNT = S.YES_RSVP_COUNT,
    T.MAYBE_RSVP_COUNT = S.MAYBE_RSVP_COUNT,
    T.WAITLIST_COUNT = S.WAITLIST_COUNT,
    T.HEADCOUNT = S.HEADCOUNT,

    T.RATING_AVERAGE = S.RATING_AVERAGE

WHEN NOT MATCHED THEN

INSERT
(
    EVENT_ID,
    DATE_KEY,
    GROUP_KEY,
    VENUE_KEY,
    YES_RSVP_COUNT,
    MAYBE_RSVP_COUNT,
    WAITLIST_COUNT,
    HEADCOUNT,
    RATING_AVERAGE
)
VALUES
(
    S.EVENT_ID,
    S.DATE_KEY,
    S.GROUP_KEY,
    S.VENUE_KEY,
    S.YES_RSVP_COUNT,
    S.MAYBE_RSVP_COUNT,
    S.WAITLIST_COUNT,
    S.HEADCOUNT,
    S.RATING_AVERAGE
);