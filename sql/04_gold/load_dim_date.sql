USE DATABASE MEETUP_DB;
USE SCHEMA GOLD;

MERGE INTO GOLD.DIM_DATE T

USING
(
    SELECT DISTINCT

        TO_NUMBER(
            TO_CHAR(
                CAST(EVENT_TIME AS DATE),
                'YYYYMMDD'
            )
        ) AS DATE_KEY,

        CAST(EVENT_TIME AS DATE) AS FULL_DATE,

        YEAR(EVENT_TIME) AS YEAR,

        QUARTER(EVENT_TIME) AS QUARTER,

        MONTH(EVENT_TIME) AS MONTH,

        MONTHNAME(EVENT_TIME) AS MONTH_NAME,

        DAY(EVENT_TIME) AS DAY,

        DAYOFWEEK(EVENT_TIME) AS DAY_OF_WEEK,

        DAYNAME(EVENT_TIME) AS DAY_NAME

    FROM SILVER.EVENTS_SILVER

    WHERE EVENT_TIME IS NOT NULL

) S

ON T.DATE_KEY = S.DATE_KEY

WHEN MATCHED
AND (
       T.FULL_DATE <> S.FULL_DATE
    OR T.YEAR <> S.YEAR
    OR T.QUARTER <> S.QUARTER
    OR T.MONTH <> S.MONTH
    OR COALESCE(T.MONTH_NAME,'') <> COALESCE(S.MONTH_NAME,'')
    OR T.DAY <> S.DAY
    OR T.DAY_OF_WEEK <> S.DAY_OF_WEEK
    OR COALESCE(T.DAY_NAME,'') <> COALESCE(S.DAY_NAME,'')
)

THEN UPDATE SET

    T.FULL_DATE = S.FULL_DATE,
    T.YEAR = S.YEAR,
    T.QUARTER = S.QUARTER,
    T.MONTH = S.MONTH,
    T.MONTH_NAME = S.MONTH_NAME,
    T.DAY = S.DAY,
    T.DAY_OF_WEEK = S.DAY_OF_WEEK,
    T.DAY_NAME = S.DAY_NAME

WHEN NOT MATCHED THEN

INSERT
(
    DATE_KEY,
    FULL_DATE,
    YEAR,
    QUARTER,
    MONTH,
    MONTH_NAME,
    DAY,
    DAY_OF_WEEK,
    DAY_NAME
)
VALUES
(
    S.DATE_KEY,
    S.FULL_DATE,
    S.YEAR,
    S.QUARTER,
    S.MONTH,
    S.MONTH_NAME,
    S.DAY,
    S.DAY_OF_WEEK,
    S.DAY_NAME
);